# -*- coding: utf-8 -*-
"""Per-experiment snapshot harness, reused by every EX-NNN experiment.

Responsibilities:
  1. Create and manage the snapshot directory results/EX-NNN/
  2. Write meta.yaml / env_snapshot.txt / command.txt / manifest.sha256
  3. Provide helpers to run and echo system commands

Design rules:
  - terminal output is mirrored line by line into terminal.log, never trimmed;
  - failures, crashes and negative results are stored as they occurred;
  - manifest.sha256 records the hash of every produced file for verification.
"""
from __future__ import annotations

import argparse
import datetime
import hashlib
import subprocess
import sys
import time
from pathlib import Path

PROJECT_ROOT = Path(__file__).resolve().parent.parent
RESULTS_DIR = PROJECT_ROOT / "results"


class ExSnapshot:
    """Snapshot directory and metadata for a single experiment run."""

    def __init__(self, ex_id: str, tag: str = "", root: Path = RESULTS_DIR):
        self.ex_id = ex_id
        self.dir = (root / ex_id).resolve()
        self.dir.mkdir(parents=True, exist_ok=True)
        self._t0 = time.time()
        self.meta = {
            "ex_id": ex_id,
            "tag": tag,
            "created_utc": time.strftime("%Y-%m-%dT%H:%M:%SZ", time.gmtime()),
            "cwd": str(Path.cwd()),
            "python": sys.version.replace("\n", " "),
            "sys_platform": sys.platform,
        }

    def set(self, **kv):
        self.meta.update(kv)
        return self

    def write_env_snapshot(self):
        """torch/cuda/cudnn/gpu + nvidia-smi + pip freeze; failures are recorded as they are."""
        lines = []
        try:
            import torch
            lines += ["=== torch ===",
                      f"version={torch.__version__}",
                      f"cuda_available={torch.cuda.is_available()}",
                      f"cuda_version={torch.version.cuda}",
                      f"cudnn_version={torch.backends.cudnn.version() if torch.backends.cudnn.is_available() else 'NA'}",
                      f"gpu={torch.cuda.get_device_name(0) if torch.cuda.is_available() else 'N/A'}",
                      f"gpu_total_mem_MB={(torch.cuda.get_device_properties(0).total_memory // 1024**2) if torch.cuda.is_available() else 'N/A'}"]
        except Exception as e:
            lines += ["[env_snapshot: torch read failed]", repr(e)]
        try:
            lines += ["=== nvidia-smi ===",
                      subprocess.run(["nvidia-smi"], capture_output=True, text=True, timeout=30).stdout]
        except Exception as e:
            lines += ["[env_snapshot: nvidia-smi failed]", repr(e)]
        try:
            lines += ["=== pip freeze ===",
                      subprocess.run([sys.executable, "-m", "pip", "freeze"],
                                     capture_output=True, text=True, timeout=120).stdout]
        except Exception as e:
            lines += ["[env_snapshot: pip freeze failed]", repr(e)]
        (self.dir / "env_snapshot.txt").write_text("\n".join(lines), encoding="utf-8")
        return self

    def write_meta(self, status: str, error=None):
        self.meta["ended_utc"] = time.strftime("%Y-%m-%dT%H:%M:%SZ", time.gmtime())
        self.meta["duration_s"] = round(time.time() - self._t0, 2)
        self.meta["status"] = status
        if error:
            self.meta["error"] = error
        (self.dir / "meta.yaml").write_text(self._yaml(self.meta), encoding="utf-8")
        return self

    @staticmethod
    def _yaml(d):
        out = []
        for k, v in d.items():
            if isinstance(v, str) and "\n" in v:
                out.append(f"{k}: |")
                for ln in v.splitlines():
                    out.append("  " + ln)
            else:
                out.append(f"{k}: {v}")
        return "\n".join(out) + "\n"

    def write_manifest(self, title: str = ""):
        rows = []
        for p in sorted(self.dir.rglob("*")):
            if p.is_file():
                rows.append(f"SHA256  {self._sha256(p)}  {p.relative_to(self.dir).as_posix()}")
        (self.dir / "manifest.sha256").write_text(
            "# manifest.sha256 (generated by exp_harness)\n"
            + (f"# {title}\n" if title else "")
            + "\n".join(rows) + "\n", encoding="utf-8")
        return self

    @staticmethod
    def _sha256(p: Path, chunk=1 << 20):
        h = hashlib.sha256()
        with open(p, "rb") as f:
            while True:
                b = f.read(chunk)
                if not b:
                    break
                h.update(b)
        return h.hexdigest()


def run(cmd, timeout=None) -> int:
    print(f"\n>> $ {cmd}", flush=True)
    return subprocess.run(cmd, shell=timeout is None).returncode


def main_harness_desc() -> argparse.ArgumentParser:
    p = argparse.ArgumentParser(description="CropRWKV experiment entry point")
    p.add_argument("--ex", required=True, help="experiment identifier, e.g. EX-001")
    p.add_argument("--tag", default="", help="experiment tag")
    p.add_argument("--seed", type=int, default=42, help="random seed")
    return p